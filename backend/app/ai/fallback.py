def answer_chat(question: str, context: dict[str, Any], lang: str = "en") -> str:
    """Grounded keyword answerer used when no LLM is configured. Only reads the context dict."""
    q = question.lower()
    sim = context.get("simulation")
    twin = context.get("twin", {})
    txt = CHAT.get(lang, CHAT["en"])
    assets = {a["id"]: a for a in twin.get("assets", [])}
    vulns = {v["id"]: v for v in twin.get("vulnerabilities", [])}
    lines: list[str] = []
    for aid, a in sorted(assets.items()):
        if aid in q:
            ports = ", ".join(f"{p['port']}/{p['service']}" for p in a["open_ports"]) or "-"
            risk = next((r for r in (sim or {}).get("asset_risks", []) if r["asset_id"] == aid), None)
            lines.append(
                f"`{aid}` ({a['asset_type']}, {a['zone']}, {a['ip']}): ports {ports}; "
                f"vulns {', '.join(a['vulnerability_ids']) or '-'}"
                + (f"; risk {risk['risk_score']:.0f}, state {risk['state']}" if risk else "")
            )
    for vid, v in sorted(vulns.items()):
        if vid in q:
            title = render_msg(Message.model_validate(v["title_i18n"]), lang) if v.get("title_i18n") else v["title"]
            lines.append(f"`{vid}`: {title} (CVSS {v['cvss']}, {v['kind']})")
    if sim is None:
        lines.append(txt["no_sim"])
    else:
        if any(w in q for w in ("score", "skor", "risk", "posture", "bal")):
            lines.append(
                f"{txt['score']}: {sim['score']:.0f}/100, p_breach {sim['p_breach']:.2f} "
                f"({render_msg(msg(f'scenario.{sim["scenario"]}'), lang)}, r{sim['revision']})."
            )
        path_words = ("path", "yol", "attack", "saldır", "hücum", "how", "nasıl", "necə")
        if any(w in q for w in path_words) and sim.get("primary_path"):
            pp = sim["primary_path"]
            steps = " → ".join(f"{s['id']} {s['technique']}" for s in pp["steps"])
            lines.append(f"{pp['id']} ({pp['likelihood']:.1%}): {steps}")
        fix_words = ("fix", "remed", "düzelt", "iyileştir", "düzəl", "first", "önce", "əvvəl", "priority", "öncelik")
        if any(w in q for w in (*fix_words, "prioritet")):
            top = [c for c in sim.get("chokepoints", []) if c["delta_score"] > 0][:3]
            if top:
                lines.append("; ".join(f"`{k['vuln_id']}` → {k['action_id']} (+{k['delta_score']:.1f})" for k in top))
    if not lines:
        lines.append(txt["no_answer"])
    return "\n".join(lines)
