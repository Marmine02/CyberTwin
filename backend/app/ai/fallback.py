def render(result: SimulationResult, comparison: Comparison | None, lang: str = "en") -> str:
    t = T.get(lang, T["en"])
    out: list[str] = [f"## {t['exec']}"]
    fmt: dict[str, Any] = {
        "scenario": render_msg(msg(f"scenario.{result.scenario.value}"), lang),
        "rev": result.revision,
        "score": result.score,
        "pb": result.p_breach,
        "pbp": result.p_breach * 100,
        "n": len(result.paths),
        "c": len(result.compromised_assets),
        "t": result.total_assets,
        "br": result.blast_radius,
        "brp": result.blast_radius * 100,
    }
    body = plural_lookup(t, "exec_body", len(result.paths)) if result.paths else t["exec_none"]
    if body is None:
        raise KeyError(f"fallback template {lang!r} has no exec_body form")
    out.append(body.format(**fmt))

    out.append(f"\n## {t['narr']}")
    p = result.primary_path
    if p is None:
        out.append(t["narr_none"])
    else:
        likp = p.likelihood * 100
        # likc: decimal comma (Azerbaijani writes 70,9%)
        likc = f"{likp:.1f}".replace(".", ",")
        out.append(t["narr_intro"].format(pid=p.id, lik=p.likelihood, likp=likp, likc=likc, goal=p.goal))
        for s in p.steps:
            out.append(
                t["step"].format(
                    sid=s.id,
                    frm=s.source,
                    to=s.to,
                    technique=s.technique,
                    vuln=f" [`{s.vuln_id}`]" if s.vuln_id else "",
                    p=s.p,
                    reason=render_msg(s.reason, lang),
                )
            )

    out.append(f"\n## {t['impact']}")
    if p is None:
        out.append(t["impact_none"])
    else:
        ranked = sorted((a for a in result.asset_risks if a.risk_score > 0), key=lambda a: (-a.risk_score, a.asset_id))
        top = ", ".join(f"`{a.asset_id}` {a.risk_score:.0f}" for a in ranked[:3]) or "-"
        out.append(t["impact_body"].format(goal=p.goal, imp=p.impact, top=top))

    out.append(f"\n## {t['remed']}")
    useful = [c for c in result.chokepoints if c.delta_score > 0]
    if not useful:
        out.append(t["remed_none"])
    for i, c in enumerate(useful[:6], start=1):
        out.append(
            t["remed_item"].format(i=i, vuln=c.vuln_id, action=c.action_id, d=c.delta_score, after=c.score_after)
        )

    out.append(f"\n## {t['best']}")
    out.append(t["best_items"])

    if comparison is not None:
        out.append(f"\n## {t['cmp']}")
        out.append(
            t["cmp_body"].format(
                b_rev=comparison.before_revision,
                a_rev=comparison.after_revision,
                before=comparison.before_score,
                after=comparison.after_score,
                delta=comparison.score_delta,
                blocked=len(comparison.blocked_paths),
                reduced=len(comparison.reduced_paths),
                new=len(comparison.new_paths),
            )
        )
        for line in comparison.changes:
            out.append(f"- {render_msg(line, lang)}")

    out.append("\n" + t["notice"])
    return "\n".join(out)


