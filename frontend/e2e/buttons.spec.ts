import { API, PAGES, SDE, expect, openApp, resetDemo, runScenario, test } from './fixtures'

test.describe('every primary button has a visible effect', () => {
  let twinId = 0
  test.beforeAll(async ({ request }) => {
    twinId = await resetDemo(request)
    await runScenario(request, twinId)
  })

  test('shell: navigation, language, notifications, help', async ({ page }) => {
    await openApp(page, '/')
    for (const [key] of PAGES) {
      await page.getByTestId(`nav-${key}`).click()
      await expect(page.getByTestId(`page-${key}`)).toBeVisible()
    }
    await page.getByTestId('lang-tr').click()
    await expect(page.locator('html')).toHaveAttribute('lang', 'tr')
    await expect(page.getByTestId('sim-badge')).toHaveText('Yalnızca simülasyon')
    await page.getByTestId('lang-az').click()
    await expect(page.getByTestId('sim-badge')).toHaveText('Yalnız simulyasiya')
    await page.getByTestId('lang-en').click()
    await expect(page.getByTestId('sim-badge')).toHaveText('Simulation only')

    await expect(page.getByTestId('notifications-badge')).toBeVisible()
    await page.getByTestId('notifications-button').click()
    await expect(page.locator('#notif-pop')).toContainText('Simulation finished on r1')
    await page.locator('#notif-pop').getByRole('button', { name: 'Mark all as read' }).click()
    await expect(page.getByTestId('notifications-badge')).toBeHidden()
    await page.keyboard.press('Escape')

    await page.getByTestId('help-button').click()
    await page.getByTestId('restart-tour').click()
    await expect(page.getByTestId('guided-tour')).toBeVisible()
    await page.getByTestId('tour-close').click()
    await expect(page.getByTestId('guided-tour')).toBeHidden()
  })

  test('overview: zone dots, scenario play buttons, panel chevrons', async ({ page, request }) => {
    await openApp(page, '/')
    await page.getByTestId('zone-dmz').click()
    await expect(page.getByTestId('node-inet')).toHaveCSS('opacity', '0.22')
    await expect(page.getByTestId('node-web-01')).toHaveCSS('opacity', '1')
    await page.getByTestId('run-credential_compromise').click()
    await expect.poll(async () => (await (await request.get(`${API}/twins/${twinId}/simulations?limit=1`)).json())[0].scenario).toBe('credential_compromise')
    await expect(page.getByTestId('panel-scenarios')).toContainText('25.2')
    await page.getByTestId('panel-critical').getByRole('link').click()
    await expect(page).toHaveURL(/\/vulnerabilities$/)
  })

  test('attack: replay controls, speed, discovery, actions', async ({ page }) => {
    await openApp(page, '/attack')
    await page.getByTestId('scenario-select').selectOption(SDE)
    await page.getByTestId('run-simulation').click()
    await expect(page.getByTestId('narration')).toBeVisible()
    await page.getByTestId('speed-4').click()
    await expect(page.getByTestId('speed-4')).toHaveAttribute('aria-checked', 'true')
    await expect(page.getByTestId('replay-done')).toBeVisible({ timeout: 20_000 })
    await page.getByTestId('play-pause').click() // replay again from the start
    await expect(page.getByTestId('replay-position')).not.toHaveText('6 / 6')
    await page.getByTestId('play-pause').click() // pause
    const pos = await page.getByTestId('replay-position').textContent()
    await page.waitForTimeout(800)
    await expect(page.getByTestId('replay-position')).toHaveText(pos ?? '')
    await page.getByTestId('step-forward').click()
    await expect(page.getByTestId('replay-position')).not.toHaveText(pos ?? '')
    await page.getByTestId('scrubber').fill('0')
    await expect(page.getByTestId('replay-position')).toHaveText('1 / 6')
    await page.getByTestId('toggle-discovery').check()
    await expect(page.getByTestId('narration')).toBeVisible()
    await expect(page.getByTestId('event-log').locator('li')).not.toHaveCount(6)
    await page.getByTestId('toggle-discovery').uncheck()
    await page.getByTestId('scenario-select').selectOption('lateral_movement')
    await expect(page.getByTestId('foothold-select')).toHaveValue('ws-01')
    await page.getByTestId('scenario-select').selectOption(SDE)
    await page.getByTestId('action-ai').click()
    await expect(page.getByTestId('page-assistant')).toBeVisible()
    await page.goBack()
    await page.getByTestId('action-report').click()
    await expect(page.getByTestId('report-frame')).toBeVisible()
    await page.goBack()
    await page.getByTestId('action-fix').click()
    await expect(page.getByTestId('page-remediation')).toBeVisible()
  })

  test('vulnerabilities fix -> remediation preselected; compare; assistant chat; reports', async ({ page }) => {
    await openApp(page, '/vulnerabilities')
    await page.getByTestId('fix-vuln:v-openssh-web01').click()
    await expect(page).toHaveURL(/\/remediation\?select=apply_patch/)
    await expect(page.getByTestId('rec-list').getByRole('checkbox', { checked: true })).toContainText('CVE-2023-38408')
    await expect(page.getByTestId('apply-button')).toContainText('Apply 1 fix')

    await page.getByTestId('select-top3').click()
    await expect(page.getByTestId('apply-button')).toContainText('Apply 3 fixes')

    await page.getByTestId('nav-assistant').click()
    await expect(page.getByTestId('ai-mode')).toContainText('Template')
    await expect(page.getByTestId('integrity-ok')).toBeVisible()
    await page.getByTestId('chat-input').fill('what should I fix first?')
    await page.getByTestId('chat-send').click()
    await expect(page.getByTestId('chat-answer').last()).toContainText('Best next fix')
    await page.getByRole('button', { name: 'Tell me about web-01' }).click()
    await expect(page.getByTestId('chat-answer').last()).toContainText('Public Web Server')

    await page.getByTestId('nav-reports').click()
    await expect(page.frameLocator('[data-testid="report-frame"]').locator('h1')).toHaveText('CyberTwin simulation report')
    const download = page.waitForEvent('download')
    await page.getByRole('link', { name: 'JSON' }).click()
    expect((await download).suggestedFilename()).toMatch(/^cybertwin-run-\d+-en\.json$/)
    const popup = page.waitForEvent('popup')
    await page.getByRole('link', { name: 'Open' }).click()
    await expect(await popup).toHaveTitle(/CyberTwin simulation report/)
    await page.getByTestId('revision-list').getByRole('button').first().click()
    await expect(page.getByText('Initial model: no earlier revision')).toBeVisible()
  })
})
