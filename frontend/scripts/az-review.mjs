// Writes docs/i18n/az_review.md: every Azerbaijani string next to its English source, with the
// strings a native reviewer should check first marked "⚠ check".
//   node scripts/az-review.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const shared = resolve(import.meta.dirname, '..', '..', 'shared', 'i18n')
const read = (f) => JSON.parse(readFileSync(resolve(shared, f), 'utf8'))
const flat = (o, p = '', out = {}) => {
  for (const [k, v] of Object.entries(o)) {
    if (v && typeof v === 'object') flat(v, `${p}${k}.`, out)
    else out[`${p}${k}`] = String(v)
  }
  return out
}
const en = { ...flat(read('en.json')), ...flat(read('ui.en.json'), 'ui.') }
const az = { ...flat(read('az.json')), ...flat(read('ui.az.json'), 'ui.') }

// Reasons a string deserves a native check (terminology chosen by the author, not a native speaker).
const UNCERTAIN = [
  [/^technique\.|^step\./, 'security technique wording'],
  [/kerberoast/i, 'loan word "Kerberoasting"'],
  [/residual|qalıq/i, '"Qalıq risk" chosen for "residual exposure"'],
  [/blast|təsir radius/i, '"Təsir radiusu" for "blast radius"'],
  [/hardening|möhkəmləndir/i, '"möhkəmləndirilməsi" for "hardening"'],
  [/chokepoint|darboğaz/i, '"darboğaz" for "chokepoint"'],
  [/foothold|dayaq/i, '"dayaq nöqtəsi" for "foothold"'],
  [/firewall/i, '"firewall" kept as loan word'],
  [/_one$|_other$/, 'plural form (az uses the singular after numbers)'],
  [/exploit|istismar/i, '"istismar" for "exploit"'],
  [/revision|revizya/i, '"revizya" for "revision"'],
  [/twin|əkiz/i, '"əkiz" for "digital twin"'],
  [/^ai\.chat\.|^ui\.ai\.s\./, 'conversational tone'],
]

const rows = Object.keys(en).sort().map((k) => {
  const reasons = UNCERTAIN.filter(([re]) => re.test(k) || re.test(az[k] ?? '')).map(([, r]) => r)
  return { k, en: en[k], az: az[k] ?? '(missing)', mark: reasons.length ? `⚠ check: ${[...new Set(reasons)].join('; ')}` : '' }
})
const esc = (s) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ')
const flagged = rows.filter((r) => r.mark).length
let md = `# Azerbaijani strings for review\n\n`
md += `Generated by \`frontend/scripts/az-review.mjs\` from \`shared/i18n\`. ${rows.length} strings, ${flagged} marked **⚠ check**.\n\n`
md += `The Azerbaijani text was written by the developer, not by a native speaker. Strings marked ⚠ use\n`
md += `terminology or grammar that a native reviewer should confirm first; unmarked strings are\n`
md += `straightforward but have not been reviewed by a native speaker either. \`{{name}}\` are placeholders\n`
md += `and must stay unchanged.\n\n`
md += `| Key | English | Azərbaycanca | Note |\n|---|---|---|---|\n`
for (const r of rows) md += `| \`${r.k}\` | ${esc(r.en)} | ${esc(r.az)} | ${r.mark} |\n`
const out = resolve(import.meta.dirname, '..', '..', 'docs', 'i18n')
mkdirSync(out, { recursive: true })
writeFileSync(resolve(out, 'az_review.md'), md, 'utf8')
console.log(`wrote docs/i18n/az_review.md (${rows.length} strings, ${flagged} flagged)`)
